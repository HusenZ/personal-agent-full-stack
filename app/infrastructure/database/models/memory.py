import uuid
from datetime import datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    Boolean,
    Computed,
    DateTime,
    Enum,
    Float,
    ForeignKey,
    Index,
    String,
    Text,
    Uuid,
    false,
    text,
)
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.domain.memory.types import (
    MemoryChange,
    MemoryDurability,
    MemorySource,
    MemoryStatus,
    MemoryType,
)
from app.infrastructure.database.models.base import Base
from app.infrastructure.database.models.mixins import TimestampMixin
from app.infrastructure.llm.embeddings import EMBEDDING_DIMENSIONS


class Memory(Base, TimestampMixin):
    """One thing the system has decided is worth remembering about a user."""

    __tablename__ = "memories"
    __table_args__ = (
        # Serves "user's usable memories", optionally by type.
        Index("ix_memories_user_id_status", "user_id", "status"),
        Index("ix_memories_user_id_type_status", "user_id", "memory_type", "status"),
        # Temporal retrieval orders a user's events by when they happened.
        Index("ix_memories_user_id_occurred_at", "user_id", "occurred_at"),
        Index("ix_memories_search_vector", "search_vector", postgresql_using="gin"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )

    content: Mapped[str] = mapped_column(Text, nullable=False)
    memory_type: Mapped[MemoryType] = mapped_column(
        Enum(MemoryType, native_enum=False, length=32), nullable=False
    )
    status: Mapped[MemoryStatus] = mapped_column(
        Enum(MemoryStatus, native_enum=False, length=32),
        nullable=False,
        default=MemoryStatus.ACTIVE,
        server_default=MemoryStatus.ACTIVE.value,
    )
    durability: Mapped[MemoryDurability] = mapped_column(
        Enum(MemoryDurability, native_enum=False, length=32), nullable=False
    )
    source: Mapped[MemorySource] = mapped_column(
        Enum(MemorySource, native_enum=False, length=32), nullable=False
    )

    importance: Mapped[float] = mapped_column(Float, nullable=False)
    confidence: Mapped[float] = mapped_column(Float, nullable=False)

    is_sensitive: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False, server_default=false()
    )

    # When it happened, not when it was recorded.
    occurred_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    # Null means it never expires.
    expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    # Points to what replaced this memory.
    superseded_by_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("memories.id", ondelete="SET NULL"), nullable=True
    )

    conversation_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("conversations.id", ondelete="SET NULL"), nullable=True
    )

    # Nullable: embedding can fail; the memory is still kept and listed.
    embedding: Mapped[list[float] | None] = mapped_column(
        Vector(EMBEDDING_DIMENSIONS), nullable=True
    )

    # Per-row model name so vectors from different models are never compared.
    embedding_model: Mapped[str | None] = mapped_column(String(100), nullable=True)

    # Generated by Postgres, so keyword search works without the embedder.
    search_vector: Mapped[str | None] = mapped_column(
        TSVECTOR,
        Computed("to_tsvector('english', content)", persisted=True),
        nullable=True,
    )

    versions: Mapped[list["MemoryVersion"]] = relationship(
        back_populates="memory", cascade="all, delete-orphan", lazy="raise"
    )


class MemoryVersion(Base):
    """A record of one change to a memory.

    History is append-only: the point of superseding rather than overwriting is
    that what the user used to believe stays answerable.
    """

    __tablename__ = "memory_versions"
    __table_args__ = (Index("ix_memory_versions_memory_id_created_at", "memory_id", "created_at"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    memory_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("memories.id", ondelete="CASCADE"), nullable=False
    )

    change: Mapped[MemoryChange] = mapped_column(
        Enum(MemoryChange, native_enum=False, length=32), nullable=False
    )

    # Full snapshot rather than a diff.
    content: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[MemoryStatus] = mapped_column(
        Enum(MemoryStatus, native_enum=False, length=32), nullable=False
    )
    importance: Mapped[float] = mapped_column(Float, nullable=False)
    confidence: Mapped[float] = mapped_column(Float, nullable=False)

    reason: Mapped[str | None] = mapped_column(String(300), nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("now()"), nullable=False
    )

    memory: Mapped[Memory] = relationship(back_populates="versions")

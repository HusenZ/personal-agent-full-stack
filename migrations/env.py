import asyncio
from logging.config import fileConfig
from typing import Any, Literal, cast

from alembic import context
from pgvector.sqlalchemy import Vector
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config
from sqlalchemy.pool import NullPool

from app.core.config import get_settings
from app.infrastructure.database.models import Base

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata

config.set_main_option("sqlalchemy.url", str(get_settings().database_url))


def _render_item(type_: str, obj: object, autogen_context: object) -> str | Literal[False]:
    """Emit vector columns with the import they need.

    Alembic renders third-party types by their fully qualified name but does not
    add the import for them, so an autogenerated vector column fails at NameError
    the first time it runs. Registering the import here fixes it for every
    migration rather than one at a time.
    """
    if type_ == "type" and isinstance(obj, Vector):
        cast(Any, autogen_context).imports.add("import pgvector.sqlalchemy")
        return f"pgvector.sqlalchemy.Vector({obj.dim})"

    return False


def _configure(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        # Without these, Alembic silently misses column type and default changes.
        compare_type=True,
        compare_server_default=True,
        render_item=_render_item,
    )


def run_migrations_offline() -> None:
    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def _run_migrations(connection: Connection) -> None:
    _configure(connection)
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    # NullPool so no connections linger after the migration.
    engine = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=NullPool,
    )

    async with engine.connect() as connection:
        await connection.run_sync(_run_migrations)

    await engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())

async def store(
    session: AsyncSession,
    owner: User,
    content: str,
    *,
    importance: float = 0.6,
    embed: bool = True,
) -> Memory:
    embeddings = FakeEmbeddingProvider()
    memory = Memory(
        id=uuid.uuid4(),
        user_id=owner.id,
        content=content,
        memory_type=MemoryType.FACT,
        status=MemoryStatus.ACTIVE,
        durability=MemoryDurability.LONG_TERM,
        source=MemorySource.CONVERSATION,
        importance=importance,
        confidence=0.9,
        embedding=(await embeddings.embed_query(content)) if embed else None,
        embedding_model=MODEL if embed else None,
    )
    session.add(memory)
    await session.commit()
    return memory


def hybrid(session: AsyncSession, **config: int | float) -> HybridMemoryRetriever:
    return HybridMemoryRetriever(
        SemanticMemoryRetriever(sessions_like(session)),
        KeywordMemoryRetriever(sessions_like(session)),
        embedding_model=MODEL,
        config=HybridConfig(**config) if config else None,  # type: ignore[arg-type]
    )


async def search(session: AsyncSession, owner: User, text: str, *, embed: bool = True, **config):
    query_embedding = await FakeEmbeddingProvider().embed_query(text) if embed else None
    return await hybrid(session, **config).retrieve(owner.id, text, query_embedding)


class TestKeywordSearch:
    async def test_stemming_matches_other_forms_of_a_word(
        self, db_session: AsyncSession, user: User
    ):
        """ "studying" should find "studied"; that is what the English config buys."""
        await store(db_session, user, "I studied graph algorithms", embed=False)

        results = await KeywordMemoryRetriever(sessions_like(db_session)).search(
            user.id, "studying", limit=5, now=datetime.now(tz=UTC)
        )

        assert [hit.content for hit in results] == ["I studied graph algorithms"]

    async def test_a_conversational_question_still_matches(
        self, db_session: AsyncSession, user: User
    ):
        """With AND semantics this would need every word of the question present."""
        await store(db_session, user, "I play the cello", embed=False)

        results = await KeywordMemoryRetriever(sessions_like(db_session)).search(
            user.id,
            "Could you remind me which instrument, the cello or violin, I play?",
            limit=5,
            now=datetime.now(tz=UTC),
        )

        assert [hit.content for hit in results] == ["I play the cello"]

    @pytest.mark.parametrize(
        "hostile",
        ["a:b & c | !d <-> (e", "'); DROP TABLE memories; --", "unbalanced 'quote", ":*"],
    )
    async def test_hostile_input_is_searched_rather_than_raising(
        self, db_session: AsyncSession, user: User, hostile: str
    ):
        await store(db_session, user, "I play the cello", embed=False)

        results = await KeywordMemoryRetriever(sessions_like(db_session)).search(
            user.id, hostile, limit=5, now=datetime.now(tz=UTC)
        )

        assert isinstance(results, list)

    async def test_the_index_is_generated_from_the_content(
        self, db_session: AsyncSession, user: User
    ):
        """Generated by the database, so it cannot drift from the text it indexes."""
        memory = await store(db_session, user, "I play the cello", embed=False)
        await db_session.execute(
            update(Memory).where(Memory.id == memory.id).values(content="I play the oboe")
        )
        await db_session.commit()

        results = await KeywordMemoryRetriever(sessions_like(db_session)).search(
            user.id, "oboe", limit=5, now=datetime.now(tz=UTC)
        )

        assert [hit.id for hit in results] == [memory.id]


class TestFusion:
    async def test_a_memory_both_retrievers_find_ranks_first(
        self, db_session: AsyncSession, user: User
    ):
        await store(db_session, user, "I play the cello in a string quartet")
        await store(db_session, user, "My quartet rehearses weekly")
        await store(db_session, user, "Strings need changing often")

        results = await search(db_session, user, "cello quartet")

        assert results[0].content == "I play the cello in a string quartet"
        assert set(results[0].sources) == {RetrievalSource.SEMANTIC, RetrievalSource.KEYWORD}

    async def test_each_result_records_where_it_came_from(
        self, db_session: AsyncSession, user: User
    ):
        await store(db_session, user, "I play the cello in a string quartet")

        results = await search(db_session, user, "cello")

        assert results[0].sources
        assert all(isinstance(source, RetrievalSource) for source in results[0].sources)

    async def test_the_output_is_bounded(self, db_session: AsyncSession, user: User):
        for index in range(15):
            await store(db_session, user, f"Cello practice note number {index}")

        results = await search(db_session, user, "cello practice", limit=4)

        assert len(results) == 4


class TestDegradation:
    async def test_keyword_search_carries_on_without_an_embedding(
        self, db_session: AsyncSession, user: User
    ):
        """A failed embedding call used to mean no recall at all. Now it costs
        recall by meaning, while recall by words still works."""
        await store(db_session, user, "I play the cello in a string quartet")

        results = await search(db_session, user, "cello", embed=False)

        assert [result.content for result in results] == ["I play the cello in a string quartet"]
        assert results[0].sources == (RetrievalSource.KEYWORD,)

    async def test_a_memory_that_was_never_embedded_is_still_findable(
        self, db_session: AsyncSession, user: User
    ):
        await store(db_session, user, "I play the cello in a string quartet", embed=False)

        results = await search(db_session, user, "cello")

        assert [result.content for result in results] == ["I play the cello in a string quartet"]


class TestScopingAppliesToBothRetrievers:
    async def test_a_superseded_memory_is_not_found_by_keyword_either(
        self, db_session: AsyncSession, user: User
    ):
        memory = await store(db_session, user, "I play the cello")
        await db_session.execute(
            update(Memory).where(Memory.id == memory.id).values(status=MemoryStatus.SUPERSEDED)
        )
        await db_session.commit()

        assert await search(db_session, user, "cello") == []

    async def test_an_expired_memory_is_not_found_by_keyword_either(
        self, db_session: AsyncSession, user: User
    ):
        memory = await store(db_session, user, "I am on a train to the cello concert")
        await db_session.execute(
            update(Memory)
            .where(Memory.id == memory.id)
            .values(expires_at=datetime.now(tz=UTC) - timedelta(days=1))
        )
        await db_session.commit()

        assert await search(db_session, user, "cello") == []

    async def test_another_users_memory_is_found_by_neither(
        self, db_session: AsyncSession, user: User
    ):
        stranger = User(id=uuid.uuid4(), email=f"{uuid.uuid4().hex}@example.com", password_hash="x")
        db_session.add(stranger)
        await db_session.commit()
        await store(db_session, stranger, "I play the cello in a string quartet")

        assert await search(db_session, user, "cello quartet") == []
